import type { Metadata, Viewport } from 'next'
import { Public_Sans, Zilla_Slab } from 'next/font/google'
import { config } from '@/config/professional'
import './globals.css'

const zilla = Zilla_Slab({
  subsets: ['latin'],
  variable: '--font-zilla',
  display: 'swap',
  weight: ['500', '600', '700'],
})

const publicSans = Public_Sans({
  subsets: ['latin'],
  variable: '--font-public',
  display: 'swap',
})

export const metadata: Metadata = {
  metadataBase: new URL(config.meta.url),
  title: config.meta.title,
  description: config.meta.description,
  openGraph: {
    title: config.meta.title,
    description: config.meta.description,
    url: config.meta.url,
    siteName: config.meta.name,
    // og:image is generated by app/opengraph-image.tsx
    type: 'website',
  },
  twitter: {
    card: 'summary_large_image',
    title: config.meta.title,
    description: config.meta.description,
  },
}

export const viewport: Viewport = {
  themeColor: '#F2F2EE',
}

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html lang="en" className={`${zilla.variable} ${publicSans.variable}`}>
      <body>{children}</body>
    </html>
  )
}
